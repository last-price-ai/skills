/** Branch prefixes agents use (AGENTS.md: `<agent>/<slug>`). */
const BRANCHES = { claude: "claude", codex: "codex", gemini: "gemini", antigravity: "gemini", copilot: "copilot", jules: "jules", cursor: "cursor", devin: "devin" }

/** Accounts that only an agent uses. Review-only bots are deliberately absent. */
const LOGINS = {
  "claude[bot]": "claude",
  "chatgpt-codex-connector[bot]": "codex",
  "copilot-swe-agent[bot]": "copilot",
  copilot: "copilot",
  "google-labs-jules[bot]": "jules",
  "cursor[bot]": "cursor",
  cursoragent: "cursor",
  "devin-ai-integration[bot]": "devin",
}

const CLAUDE_FOOTER = /Generated (?:with|by) \[Claude Code\]|claude\.ai\/code\/(?:session_|project\/)/i
const SIGN_OFF = /^\s*(?:CLAIM|REPORT|READY|QUESTION|FAILURE|DONE|HANDOFF|DECISION):/i

/** The agent a name like "Codex" or "Antigravity" stands for, or null. */
export function agentNamed(name) {
  const n = String(name ?? "").trim().toLowerCase()
  for (const [key, a] of Object.entries(AGENTS)) if (a.signs.includes(n)) return key
  return null
}

/** Agents a branch name points at. */
export function fromBranch(ref) {
  const prefix = String(ref ?? "").split("/")[0].toLowerCase()
  return BRANCHES[prefix] ? [BRANCHES[prefix]] : []
}

/** The agent behind a GitHub login, or null. */
export function fromLogin(login) {
  return LOGINS[String(login ?? "").toLowerCase()] ?? null
}

/**
 * Agents and Claude accounts a piece of text (a body, a comment, a commit
 * message) shows. Text with Claude's footer is Claude's, so a Claude comment
 * quoting "CLAIM: … (Codex)" does not label Codex.
 */
export function fromText(text) {
  const s = String(text ?? "")
  const agents = new Set()
  const accounts = new Set()
  const claude = CLAUDE_FOOTER.test(s) || /Co-Authored-By:\s*Claude\b/i.test(s) || /noreply@anthropic\.com/i.test(s)
  if (claude) {
    agents.add("claude")
    for (const m of s.matchAll(/claude\.ai\/code\/project\/(chan_[A-Za-z0-9]+)/g)) if (CLAUDE_ACCOUNTS[m[1]]) accounts.add(CLAUDE_ACCOUNTS[m[1]])
  }
  for (const m of s.matchAll(/^Co-authored-by:\s*([^<\n]+)</gim)) {
    const who = m[1].trim().toLowerCase()
    for (const key of Object.keys(AGENTS)) if (AGENTS[key].signs.some((n) => who === n || who.startsWith(`${n} `))) agents.add(key)
  }
  if (!claude) {
    const first = s.split("\n").find((l) => l.trim()) ?? ""
    if (SIGN_OFF.test(first)) {
      // "(Codex)", "(Codex marketplace fix)", "(Antigravity / Gemini)", or the
      // agent as the subject: "REPORT: Codex completed…".
      const names = [...first.matchAll(/\(\s*([A-Za-z]+)(?:\s*\/\s*([A-Za-z]+))?/g)].flatMap((m) => [m[1], m[2]])
      names.push(first.match(/^\s*[A-Z ]+:\s*([A-Za-z]+)/)?.[1])
      for (const n of names) { const a = agentNamed(n); if (a) agents.add(a) }
    }
    for (const m of s.matchAll(/(?:^|\s)Agent:\s*([A-Za-z][A-Za-z]+)/gim)) { const a = agentNamed(m[1]); if (a) agents.add(a) }
  }
  return { agents, accounts }
}

/** The #N an agent's sign-off names on its first line (the items it worked on). */
export function signOffRefs(text) {
  const s = String(text ?? "")
  if (CLAUDE_FOOTER.test(s)) return []
  const first = s.split("\n").find((l) => l.trim()) ?? ""
  if (!SIGN_OFF.test(first)) return []
  return [...new Set([...first.matchAll(/#(\d+)\b/g)].map((m) => Number(m[1])))]
}

/** Issues a PR body closes or is part of. */
export function linkedIssues(body) {
  const s = String(body ?? "")
  return [...new Set([...s.matchAll(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?|part of|refs?)\s*:?\s+#(\d+)\b/gi)].map((m) => Number(m[1])))]
}

/**
 * Everything one issue or PR shows. `item` is the issue (from /issues),
 * `pull` the PR (from /pulls, or null), plus its comments, reviews and commits.
 */
export function detect({ item, pull = null, comments = [], reviews = [], commits = [] }) {
  const agents = new Set()
  const accounts = new Set()
  const add = (r) => { for (const a of r.agents) agents.add(a); for (const a of r.accounts) accounts.add(a) }
  const login = (u) => { const a = fromLogin(u?.login); if (a) agents.add(a) }
  if (pull) for (const a of fromBranch(pull.head?.ref)) agents.add(a)
  login(item.user)
  add(fromText(item.body))
  for (const c of comments) { login(c.user); add(fromText(c.body)) }
  for (const r of reviews) { login(r.user); add(fromText(r.body)) }
  for (const c of commits) {
    login(c.author)
    login(c.committer)
    add(fromText(c.commit?.message))
  }
  return { agents, accounts }
}

/** The labels for a set of agents and Claude accounts, in a stable order. */
export function labelsFor(agents, accounts = new Set()) {
  const out = Object.keys(AGENTS).filter((k) => agents.has(k)).map((k) => AGENTS[k].label)
  if (agents.has("claude")) for (const k of Object.keys(ACCOUNT_LABELS)) if (accounts.has(k)) out.push(ACCOUNT_LABELS[k].label)
  return out
}

/** "Claude (work account), Codex" for the board field, from label names. */
export function agentsText(labelNames) {
  const names = new Set(labelNames)
  const parts = []
  for (const a of Object.values(AGENTS)) {
    if (!names.has(a.label)) continue
    if (a === AGENTS.claude) {
      const acc = Object.entries(ACCOUNT_LABELS).filter(([, v]) => names.has(v.label)).map(([k]) => k)
      parts.push(acc.length ? `Claude (${acc.join(" + ")})` : "Claude")
    } else parts.push(a.name)
  }
  return parts.join(", ")
}

/** The agent names on a list of labels ("Claude", "Codex"), for the merge train board. */
export function agentNames(labels) {
  const names = new Set((labels ?? []).map((l) => (typeof l === "string" ? l : l?.name)))
  return Object.values(AGENTS).filter((a) => names.has(a.label)).map((a) => a.name)
}

// ---------------------------------------------------------------- Handoff activity

export const HANDOFF_TITLE = "Agent handoff"
const HANDOFF_BEGIN = "<!-- agent-activity:begin -->"
const HANDOFF_END = "<!-- agent-activity:end -->"
const DAYS = 14
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
const dayLabel = (k) => `${Number(k.slice(8))} ${MONTHS[Number(k.slice(5, 7)) - 1]}`

/** How the hand-off works, as a diagram (docs/agents/other-agents.md in pictures). */
export const HANDOFF_FLOW = `\`\`\`mermaid
flowchart LR
  pick["Agent picks an issue or PR<br/>(Claude, Codex, Gemini…)"] --> claim["CLAIM: #N (Agent)<br/>comment here"]
  claim --> taken{"Claimed by<br/>someone else?"}
  taken -- yes --> ask["QUESTION: to the owner<br/>of the claim"]
  taken -- no --> work["Works on branch<br/>agent/slug"]
  work --> pr["Opens or updates a PR"]
  pr --> report["REPORT: #N -> PR #M (Agent)"]
  report --> train["merge-train label<br/>(Merge train issue)"]
  train --> main(["Merged into main"])
  claim -. read by .-> labels["Agent labels workflow"]
  report -. read by .-> labels
  pr -. branch, footer, trailers .-> labels
  labels --> tags["agent:* labels on the issue and PR<br/>+ Agents field on the project board"]
\`\`\``

/** The kind of post a hand-off comment is: its sign-off word, or "other". */
export function postKind(body) {
  const first = String(body ?? "").split("\n").find((l) => l.trim()) ?? ""
  const m = first.match(/^\s*(CLAIM|REPORT|QUESTION|FAILURE|READY|DECISION|DONE|HANDOFF):/i)
  return m ? m[1].toUpperCase() : "other"
}

/** Who posted a hand-off comment: the agent its text shows, else "Unsigned". */
function poster(c) {
  const agent = fromLogin(c.user?.login) ?? [...fromText(c.body).agents][0]
  return agent ? AGENTS[agent].name : "Unsigned"
}

/**
 * The hand-off issue's activity block: posts per day, claims and reports by
 * agent, and the flow diagram. Built from the comments themselves, so it
 * needs no stored history.
 */
export function handoffActivity(comments, now = new Date().toISOString()) {
  const end = Date.parse(now.slice(0, 10))
  const keys = Array.from({ length: DAYS }, (_, i) => new Date(end - (DAYS - 1 - i) * 86400000).toISOString().slice(0, 10))
  const days = Object.fromEntries(keys.map((k) => [k, { total: 0, CLAIM: 0, REPORT: 0, QUESTION: 0, rest: 0, who: {} }]))
  const byAgent = {}
  for (const c of comments) {
    const d = days[String(c.created_at ?? "").slice(0, 10)]
    if (!d) continue
    const kind = postKind(c.body)
    const who = poster(c)
    d.total += 1
    if (kind in d && kind !== "total" && kind !== "who" && kind !== "rest") d[kind] += 1
    else d.rest += 1
    d.who[who] = (d.who[who] ?? 0) + 1
    byAgent[who] = (byAgent[who] ?? 0) + 1
  }
  const series = keys.map((k) => days[k].total)
  const chart = `\`\`\`mermaid
xychart-beta
  title "Posts on this issue per day"
  x-axis [${keys.map((k) => `"${dayLabel(k)}"`).join(", ")}]
  y-axis "posts" 0 --> ${Math.max(1, ...series)}
  bar [${series.join(", ")}]
\`\`\``
  const pie = Object.keys(byAgent).length
    ? `\n\n\`\`\`mermaid\npie showData title Posts by agent, last ${DAYS} days\n${Object.entries(byAgent).sort((a, b) => b[1] - a[1]).map(([n, c]) => `  "${n}" : ${c}`).join("\n")}\n\`\`\``
    : ""
  const rows = keys
    .slice()
    .reverse()
    .filter((k) => days[k].total)
    .map((k) => {
      const d = days[k]
      const who = Object.entries(d.who).sort((a, b) => b[1] - a[1]).map(([n, c]) => `${n} ${c}`).join(", ")
      return `| ${dayLabel(k)} | ${d.total} | ${d.CLAIM} | ${d.REPORT} | ${d.QUESTION} | ${d.rest} | ${who} |`
    })
    .join("\n")
  return `${HANDOFF_BEGIN}
## Activity, last ${DAYS} days

Rewritten by the Agent labels workflow after each comment here and once a day. Edit anything above this section; this section is replaced.

${HANDOFF_FLOW}

${chart}${pie}

| Day | Posts | Claims | Reports | Questions | Other | By agent |
|-----|-------|--------|---------|-----------|-------|----------|
${rows || "| | | | | | | |"}
${HANDOFF_END}`
}

/** The body with its activity block replaced, or added at the end. */
export function withActivity(body, block) {
  const s = String(body ?? "")
  const i = s.indexOf(HANDOFF_BEGIN)
  const j = s.indexOf(HANDOFF_END)
  if (i >= 0 && j > i) return s.slice(0, i) + block + s.slice(j + HANDOFF_END.length)
  return `${s.trimEnd()}\n\n${block}\n`
}

/** Rewrites the activity block on the open "Agent handoff" issue, if there is one. */
export async function updateHandoff(api, { log = console.log, issue = null } = {}) {
  if (!issue) {
    const open = await api.all("/issues?state=open&per_page=100", 5)
    issue = open.find((i) => !i.pull_request && i.title === HANDOFF_TITLE)
  }
  if (!issue) return false
  const since = new Date(Date.now() - DAYS * 86400000).toISOString()
  const comments = await api.all(`/issues/${issue.number}/comments?since=${since}&per_page=100`, 20)
  // Re-read just before writing: Claude threads edit this body by hand.
  const fresh = await api.get(`/issues/${issue.number}`)
  const body = withActivity(fresh.body, handoffActivity(comments))
  if (body === fresh.body) return false
  await api.write("PATCH", `/issues/${issue.number}`, { body })
  log(`#${issue.number}: activity section rewritten`)
  return true
}

// ---------------------------------------------------------------- GitHub

function client({ token, repo, dryRun = false, log = console.log }) {
  const base = `https://api.github.com/repos/${repo}`
  let remaining = Infinity
  async function call(method, path, body) {
    const url = path.startsWith("https://") ? path : `${base}${path}`
    const res = await fetch(url, {
      method,
      headers: { authorization: `Bearer ${token}`, accept: "application/vnd.github+json", "x-github-api-version": "2022-11-28", "user-agent": "agent-labels" },
      body: body ? JSON.stringify(body) : undefined,
    })
    remaining = Number(res.headers.get("x-ratelimit-remaining") ?? remaining)
    const text = await res.text()
    const data = text ? JSON.parse(text) : null
    return { status: res.status, data, next: (res.headers.get("link") ?? "").match(/<([^>]+)>;\s*rel="next"/)?.[1] ?? null }
  }
  return {
    get remaining() { return remaining },
    async get(path) {
      const r = await call("GET", path)
      if (r.status >= 400) throw new Error(`GET ${path}: ${r.status} ${r.data?.message ?? ""}`)
      return r.data
    },
    async all(path, limit = 30) {
      const out = []
      let url = path
      for (let i = 0; url && i < limit; i++) {
        const r = await call("GET", url)
        if (r.status >= 400) throw new Error(`GET ${url}: ${r.status} ${r.data?.message ?? ""}`)
        out.push(...(Array.isArray(r.data) ? r.data : []))
        url = r.next
      }
      return out
    },
    async write(method, path, body) {
      if (dryRun) { log(`[dry run] ${method} ${path} ${JSON.stringify(body)}`); return { status: 200 } }
      const r = await call(method, path, body)
      if (r.status >= 400 && r.status !== 422) throw new Error(`${method} ${path}: ${r.status} ${r.data?.message ?? ""}`)
      return r
    },
  }
}

/** Creates any agent label the repository does not have yet. */
async function ensureLabels(api, wanted, known) {
  const all = [...Object.values(AGENTS), ...Object.values(ACCOUNT_LABELS)]
  for (const name of wanted) {
    if (known.has(name)) continue
    const def = all.find((a) => a.label === name)
    await api.write("POST", "/labels", { name, color: def.color, description: `${def.name} worked on this (set by the Agent labels workflow)` })
    known.add(name)
  }
}

/** Reads an item and everything on it. */
async function gather(api, number, cache = {}) {
  const item = cache.item ?? (await api.get(`/issues/${number}`))
  const comments = cache.comments ?? (item.comments ? await api.all(`/issues/${number}/comments?per_page=100`) : [])
  let pull = null
  let reviews = []
  let commits = []
  if (item.pull_request) {
    pull = cache.pull ?? (await api.get(`/pulls/${number}`))
    reviews = cache.skipReviews ? [] : await api.all(`/pulls/${number}/reviews?per_page=100`, 3)
    commits = await api.all(`/pulls/${number}/commits?per_page=100`, 3)
  }
  return { item, pull, comments, reviews, commits }
}

/** Board writer: the "Agents" text field on a Project (v2), or null when not configured. */
function projectWriter({ url, token, log }) {
  const m = String(url ?? "").match(/\/(orgs|users)\/([^/]+)\/projects\/(\d+)/)
  if (!m || !token) return null
  const [, kind, owner, number] = m
  const ownerField = kind === "orgs" ? "organization" : "user"
  async function gql(query, variables) {
    const res = await fetch("https://api.github.com/graphql", {
      method: "POST",
      headers: { authorization: `Bearer ${token}`, "content-type": "application/json", "user-agent": "agent-labels" },
      body: JSON.stringify({ query, variables }),
    })
    const out = await res.json()
    if (out.errors?.length) throw new Error(out.errors.map((e) => e.message).join("; "))
    return out.data
  }
  let project = null
  async function load() {
    if (project) return project
    const q = await gql(`query($o:String!,$n:Int!){ ${ownerField}(login:$o){ projectV2(number:$n){ id fields(first:100){ nodes { ... on ProjectV2FieldCommon { id name } } } } } }`, { o: owner, n: Number(number) })
    const p = q[ownerField]?.projectV2
    if (!p) throw new Error(`Project ${url} not found`)
    let field = p.fields.nodes.find((f) => f?.name === "Agents")
    if (!field) {
      const c = await gql(`mutation($p:ID!){ createProjectV2Field(input:{projectId:$p,dataType:TEXT,name:"Agents"}){ projectV2Field { ... on ProjectV2FieldCommon { id name } } } }`, { p: p.id })
      field = c.createProjectV2Field.projectV2Field
      log(`Created the "Agents" field on ${url}`)
    }
    project = { id: p.id, field: field.id }
    return project
  }
  return async function write(nodeId, open, text) {
    const p = await load()
    let itemId = null
    const q = await gql(`query($c:ID!){ node(id:$c){ ... on Issue { projectItems(first:50){ nodes { id project { id } } } } ... on PullRequest { projectItems(first:50){ nodes { id project { id } } } } } }`, { c: nodeId })
    itemId = (q.node?.projectItems?.nodes ?? []).find((n) => n.project?.id === p.id)?.id ?? null
    if (!itemId && open) {
      try {
        const a = await gql(`mutation($p:ID!,$c:ID!){ addProjectV2ItemById(input:{projectId:$p,contentId:$c}){ item { id } } }`, { p: p.id, c: nodeId })
        itemId = a.addProjectV2ItemById.item.id
      } catch (e) {
        if (!/already exists/i.test(e.message)) throw e
        return write(nodeId, false, text)
      }
    }
    if (!itemId) return false
    await gql(`mutation($p:ID!,$i:ID!,$f:ID!,$t:String!){ updateProjectV2ItemFieldValue(input:{projectId:$p,itemId:$i,fieldId:$f,value:{text:$t}}){ clientMutationId } }`, { p: p.id, i: itemId, f: p.field, t: text })
    return true
  }
}

/**
 * Labels the given items, plus the issues their PRs link and the items their
 * sign-offs name. Returns { labelled: [[number, added labels]] }.
 */
export async function labelItems(api, numbers, { log = console.log, board = null, cache = new Map(), known = null, signOffs = null } = {}) {
  known ??= new Set((await api.all("/labels?per_page=100")).map((l) => l.name))
  const extra = new Map() // number -> { agents, accounts } pushed from elsewhere
  const push = (n, r) => {
    const e = extra.get(n) ?? { agents: new Set(), accounts: new Set() }
    for (const a of r.agents) e.agents.add(a)
    for (const a of r.accounts) e.accounts.add(a)
    extra.set(n, e)
  }
  const found = new Map()
  for (const n of numbers) {
    if (api.remaining < 100) {
      log(`::warning::Stopping early to keep the API allowance: ${api.remaining} calls left this hour. Run the sweep again later for the rest.`)
      break
    }
    let g
    try {
      g = await gather(api, n, cache.get(n))
    } catch (e) {
      log(`::warning::#${n}: ${e.message}`)
      continue
    }
    const r = detect(g)
    found.set(n, { r, item: g.item })
    if (g.pull) for (const i of linkedIssues(g.item.body)) if (i !== n) push(i, r)
    // On a comment event only the new comment's sign-off is followed: the
    // handoff issue holds hundreds, and the daily sweep follows them all.
    for (const c of signOffs ?? g.comments) {
      const refs = signOffRefs(c.body)
      if (!refs.length) continue
      const s = fromText(c.body)
      for (const i of refs) if (i !== n) push(i, s)
    }
  }
  for (const [n, e] of extra) {
    if (!found.has(n)) {
      try {
        found.set(n, { r: { agents: new Set(), accounts: new Set() }, item: await api.get(`/issues/${n}`) })
      } catch {
        continue // a #N that is not an issue here (a comment id, another repo)
      }
    }
    const f = found.get(n).r
    for (const a of e.agents) f.agents.add(a)
    for (const a of e.accounts) f.accounts.add(a)
  }
  const labelled = []
  for (const [n, { r, item }] of found) {
    const have = new Set((item.labels ?? []).map((l) => l.name))
    const add = labelsFor(r.agents, r.accounts).filter((l) => !have.has(l))
    if (add.length) {
      await ensureLabels(api, add, known)
      await api.write("POST", `/issues/${n}/labels`, { labels: add })
      log(`#${n}: added ${add.join(", ")}`)
      labelled.push([n, add])
    }
    const all = [...have, ...add].filter((l) => l.startsWith("agent:") || l.startsWith("claude:"))
    if (board && all.length && (add.length || process.env.AGENT_LABELS_BOARD_ALL === "1")) {
      try {
        await board(item.node_id, item.state === "open", agentsText(all))
      } catch (e) {
        log(`::warning::#${n}: could not set the board's Agents field: ${e.message}`)
      }
    }
  }
  return { labelled }
}

/** The items an Actions event is about. */
export function eventItems(name, payload) {
  const n = payload.pull_request?.number ?? payload.issue?.number
  return n ? [n] : []
}

/** Every issue and PR updated in the last `days` days, newest first. */
async function recentItems(api, days) {
  const since = new Date(Date.now() - days * 86400000).toISOString()
  const items = await api.all(`/issues?state=all&since=${since}&per_page=100&sort=updated`, 50)
  return items
}

async function main() {
  const [mode = "event", ...rest] = process.argv.slice(2)
  const token = process.env.GITHUB_TOKEN
  const repo = process.env.GITHUB_REPOSITORY
  if (!token || !repo) throw new Error("GITHUB_TOKEN and GITHUB_REPOSITORY are required")
  const log = (m) => console.log(m)
  const api = client({ token, repo, dryRun: process.env.DRY_RUN === "1", log })
  const board = projectWriter({ url: process.env.PROJECT_URL, token: process.env.PROJECT_TOKEN, log })
  if (!board) log("No PROJECT_URL/PROJECT_TOKEN: labels only, no board field.")
  let numbers = []
  const cache = new Map()
  let signOffs = null
  if (mode === "event") {
    const payload = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, "utf8"))
    numbers = eventItems(process.env.GITHUB_EVENT_NAME, payload)
    if (payload.comment) signOffs = [payload.comment]
  } else if (mode === "sweep") {
    const days = Number(rest[0] ?? 2)
    const items = await recentItems(api, Number.isFinite(days) && days > 0 ? days : 2)
    // One list call per 100 PRs gives each its branch, instead of a call per PR.
    // Reviews are skipped here: they only ever add Claude, which the footer
    // on Claude's own PR body or comments already shows.
    const since = Date.now() - (Number.isFinite(days) && days > 0 ? days : 2) * 86400000
    const pulls = new Map()
    for (let page = 1; page <= 20; page++) {
      const batch = await api.get(`/pulls?state=all&sort=updated&direction=desc&per_page=100&page=${page}`)
      for (const p of batch) pulls.set(p.number, p)
      if (batch.length < 100 || Date.parse(batch.at(-1).updated_at) < since) break
    }
    for (const i of items) cache.set(i.number, { item: i, pull: pulls.get(i.number), skipReviews: true })
    numbers = items.map((i) => i.number)
    log(`Sweeping ${numbers.length} issues and PRs updated in the last ${days} days.`)
  } else if (mode === "item") {
    numbers = rest.map(Number).filter((n) => n > 0)
  } else throw new Error(`Unknown mode ${mode}: use event, sweep or item`)
  const { labelled } = await labelItems(api, numbers, { log, board, cache, signOffs })
  // The hand-off issue's activity section: after a comment on it, and on every sweep.
  const commented = mode === "event" && signOffs ? cache.get(numbers[0])?.item ?? (await api.get(`/issues/${numbers[0]}`)) : null
  if (mode === "sweep" || mode === "item" || commented?.title === HANDOFF_TITLE) {
    try {
      await updateHandoff(api, { log, issue: commented?.title === HANDOFF_TITLE ? commented : null })
    } catch (e) {
      log(`::warning::Could not update the hand-off activity section: ${e.message}`)
    }
  }
  log(`Done: ${labelled.length} item(s) labelled. API calls left this hour: ${api.remaining}.`)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main().catch((e) => {
    console.error(`::error::${e.message}`)
    process.exit(1)
  })
}
