#!/usr/bin/env node
/**
 * Labels issues and pull requests with the agents that worked on them:
 * `agent:claude`, `agent:codex`, `agent:gemini` and so on, several on one
 * item when several agents touched it. Claude work that carries a claude.ai
 * project link also gets `claude:work` or `claude:personal`, for the
 * account it came from.
 *
 * Every PR and issue here is opened with the owner's GitHub account, so the
 * author says nothing. What does:
 *   - the branch: `claude/…`, `codex/…`, `gemini/…`, `copilot/…` (AGENTS.md)
 *   - bot accounts that open PRs or push commits (Copilot coding agent, Jules…)
 *   - Claude's footer ("Generated by/with Claude Code") and claude.ai links
 *   - commit trailers (`Co-Authored-By: Claude …`, Cursor Agent…)
 *   - the hand-off sign-offs from docs/agents/other-agents.md:
 *     `CLAIM: #1513 (Codex)`, `REPORT: #1133 -> PR #1569 (Antigravity)`,
 *     `Agent: Codex …` in a PR body. A sign-off labels every #N on its
 *     first line, so the issue an agent claimed gets the agent too.
 * A PR's agents also go on the issues it closes or is part of.
 *
 * Labels are only ever added: an agent that worked on an item stays on it.
 * Review bots (Copilot review, cubic) are left out on purpose, since they
 * review every PR and would label all of them.
 *
 * With PROJECT_URL and PROJECT_TOKEN set, the same list is written to a
 * text field "Agents" on that Project (v2) board, created if missing.
 *
 *   node scripts/agent-labels.mjs event          # from a GitHub Actions event
 *   node scripts/agent-labels.mjs sweep [days]   # everything updated in N days (default 2)
 *   node scripts/agent-labels.mjs item <n>...    # specific issues or PRs
 *
 * Env: GITHUB_TOKEN, GITHUB_REPOSITORY, and for events GITHUB_EVENT_NAME and
 * GITHUB_EVENT_PATH. DRY_RUN=1 prints what it would add.
 */
import { readFileSync } from "node:fs"
import { pathToFileURL } from "node:url"

